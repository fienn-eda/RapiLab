// 우리가 쓴 상수라 임의 HTML을 다룰 위험이 없다.
//
// 여기 오지 않는 것: 단위 표시("초", "%")는 라벨의 일부이고, 진행·결과·에러
// 메시지는 안내가 아니라 그 순간의 상태 보고다. 섞이면 무엇을 고쳐도 되는지가
// 흐려진다.

