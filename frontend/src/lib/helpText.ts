// 문자열만 받는 자리(title 속성, window.confirm, 에러 상태)로 가므로 별표가
// 글자 그대로 보인다.
//
// 값이 끼는 문구는 함수다. 자리표시자 문자열을 쓰지 않는 이유는 조용히 틀리기
// 때문이다 - 이름을 오타 내도 컴파일러가 말이 없고 화면에 자리표시자가 박힌다.
// 포맷 헬퍼(percent, formatDamage)를 통과한 값은 문자열로 받고, 그 밖의 값은
